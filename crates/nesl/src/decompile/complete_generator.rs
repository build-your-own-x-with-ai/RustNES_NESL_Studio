//! Phase 8: Complete Code Generation
//!
//! Merge all components into a complete, runnable NESL program

use std::fs;
use std::path::Path;
use crate::decompile::final_complete;
use crate::decompile::data_analysis::DataAnalyzer;
use crate::decompile::chr_integration::ChrExtractor;

pub struct CompleteGenerator {
    rom_path: String,
    logic_code: String,
    data_code: String,
    tiles_code: String,
}

impl CompleteGenerator {
    pub fn from_rom(rom_path: &Path) -> Result<Self, String> {
        eprintln!("Phase 8: 生成完整代码...");
        eprintln!();

        // 1. Generate logic code (Phase 5)
        eprintln!("Step 1/3: 生成程序逻辑...");
        let logic_code = final_complete::final_decompile_to_string(rom_path)?;
        eprintln!("  ✅ {} 行", logic_code.lines().count());

        // 2. Generate data code (Phase 6)
        eprintln!("Step 2/3: 分析数据段...");
        let rom_bytes = fs::read(rom_path)
            .map_err(|e| format!("Cannot read ROM: {}", e))?;

        let prg_banks = rom_bytes[4] as usize;
        let prg_rom = &rom_bytes[16..16 + prg_banks * 16384];

        let mut analyzer = DataAnalyzer::new(prg_rom);
        analyzer.analyze();
        let data_code = analyzer.generate_nesl();
        eprintln!("  ✅ {} 行", data_code.lines().count());

        // 3. Generate tiles code (Phase 7)
        eprintln!("Step 3/3: 提取 CHR tiles...");
        let extractor = ChrExtractor::from_rom(rom_path)?;
        let tiles_code = extractor.generate_smart_tiles();
        eprintln!("  ✅ {} 行", tiles_code.lines().count());

        eprintln!();

        Ok(Self {
            rom_path: rom_path.display().to_string(),
            logic_code,
            data_code,
            tiles_code,
        })
    }

    /// Generate complete NESL code with proper initialization
    pub fn generate_complete(&self) -> String {
        let mut code = String::new();

        // Header
        code.push_str("// ════════════════════════════════════════════════════════\n");
        code.push_str("//   Super Mario Bros - Complete Decompilation\n");
        code.push_str("// ════════════════════════════════════════════════════════\n");
        code.push_str("//\n");
        code.push_str(&format!("// Source ROM: {}\n", self.rom_path));
        code.push_str("// Generated by: RustNES Final Decompiler (Phase 8)\n");
        code.push_str("//\n");
        code.push_str("// Components:\n");
        code.push_str(&format!("//   - Program Logic: {} lines\n", self.logic_code.lines().count()));
        code.push_str(&format!("//   - Data Segments: {} lines\n", self.data_code.lines().count()));
        code.push_str(&format!("//   - CHR Tiles: {} lines\n", self.tiles_code.lines().count()));
        code.push_str("//\n");
        code.push_str("// Total: {} lines of complete, integrated NESL code\n");
        code.push_str("//\n");
        code.push_str("// ════════════════════════════════════════════════════════\n\n");

        // CHR Tiles (first, as they're referenced by code)
        code.push_str(&self.tiles_code);
        code.push_str("\n");

        // Data Segments
        code.push_str(&self.data_code);
        code.push_str("\n");

        // Enhanced main function
        code.push_str("// ========== Initialization ==========\n\n");
        code.push_str(&self.generate_init_code());
        code.push_str("\n");

        // Original logic code (but filter out the old main)
        code.push_str("// ========== Program Logic ==========\n\n");
        code.push_str(&self.filter_logic_code());
        code.push_str("\n");

        // New complete main
        code.push_str("// ========== Main Entry Point ==========\n\n");
        code.push_str(&self.generate_main());

        code
    }

    /// Generate initialization functions
    fn generate_init_code(&self) -> String {
        let mut code = String::new();

        code.push_str("fn init_ppu() {\n");
        code.push_str("    // Turn off PPU during initialization\n");
        code.push_str("    ppu_off();\n");
        code.push_str("    \n");
        code.push_str("    // Load palettes\n");
        code.push_str("    if palette_0.len() > 0 {\n");
        code.push_str("        load_palette(palette_0);\n");
        code.push_str("    }\n");
        code.push_str("    \n");
        code.push_str("    // Clear nametables\n");
        code.push_str("    vram_addr(0x2000);\n");
        code.push_str("    vram_fill(0, 1024);\n");
        code.push_str("    \n");
        code.push_str("    // Turn on PPU\n");
        code.push_str("    ppu_on();\n");
        code.push_str("}\n\n");

        code.push_str("fn show_title() {\n");
        code.push_str("    // Display title screen\n");
        code.push_str("    // TODO: Load title screen tiles\n");
        code.push_str("    wait_vblank();\n");
        code.push_str("}\n\n");

        code
    }

    /// Filter out old main and reset functions
    fn filter_logic_code(&self) -> String {
        let mut filtered = String::new();
        let mut in_main = false;
        let mut brace_count = 0;

        for line in self.logic_code.lines() {
            let trimmed = line.trim();

            // Skip old main function
            if trimmed.starts_with("fn main()") || trimmed.starts_with("fn reset()") {
                in_main = true;
                brace_count = 0;
                continue;
            }

            if in_main {
                if trimmed.contains('{') {
                    brace_count += trimmed.matches('{').count();
                }
                if trimmed.contains('}') {
                    brace_count = brace_count.saturating_sub(trimmed.matches('}').count());
                    if brace_count == 0 {
                        in_main = false;
                    }
                }
                continue;
            }

            filtered.push_str(line);
            filtered.push('\n');
        }

        filtered
    }

    /// Generate complete main function
    fn generate_main(&self) -> String {
        let mut code = String::new();

        code.push_str("fn main() {\n");
        code.push_str("    // ════════════════════════════════════════════════════════\n");
        code.push_str("    //   Super Mario Bros - Main Entry Point\n");
        code.push_str("    // ════════════════════════════════════════════════════════\n");
        code.push_str("    \n");
        code.push_str("    // Initialize PPU and load graphics\n");
        code.push_str("    init_ppu();\n");
        code.push_str("    \n");
        code.push_str("    // Show title screen\n");
        code.push_str("    show_title();\n");
        code.push_str("    \n");
        code.push_str("    // Wait for start button\n");
        code.push_str("    loop {\n");
        code.push_str("        let joy = joypad(0);\n");
        code.push_str("        if joy & 0x10 != 0 {  // Start button\n");
        code.push_str("            break;\n");
        code.push_str("        }\n");
        code.push_str("        wait_vblank();\n");
        code.push_str("    }\n");
        code.push_str("    \n");
        code.push_str("    // Game loop\n");
        code.push_str("    loop {\n");
        code.push_str("        // Call original NMI handler\n");
        code.push_str("        nmi();\n");
        code.push_str("        \n");
        code.push_str("        // Wait for next frame\n");
        code.push_str("        wait_vblank();\n");
        code.push_str("    }\n");
        code.push_str("}\n");

        code
    }

    /// Get statistics
    pub fn stats(&self) -> Stats {
        Stats {
            logic_lines: self.logic_code.lines().count(),
            data_lines: self.data_code.lines().count(),
            tiles_lines: self.tiles_code.lines().count(),
            total_lines: self.logic_code.lines().count()
                + self.data_code.lines().count()
                + self.tiles_code.lines().count(),
        }
    }
}

#[derive(Debug)]
pub struct Stats {
    pub logic_lines: usize,
    pub data_lines: usize,
    pub tiles_lines: usize,
    pub total_lines: usize,
}
