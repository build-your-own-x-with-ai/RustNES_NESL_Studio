//! Complete Integrated Decompiler
//!
//! Combines all phases (1-4) into a complete decompilation pipeline:
//! Phase 1: Analysis
//! Phase 2: Enhanced pseudocode
//! Phase 3: Register elimination + optimization
//! Phase 4: High-level code generation
//! Phase 5: Testing and validation

use std::collections::{HashMap, BTreeMap};
use crate::disasm::{Disassembler, Instruction};
use super::advanced::{Variable, Function, scan_zeropage_accesses, infer_variables, infer_functions};
use super::register_elimination::{RegisterEliminator, Statement};
use super::dataflow::{DataFlowAnalyzer, VariablePropagator};
use super::high_level_codegen::{HighLevelCodeGen, ParameterDetector};

/// Complete decompiler integrating all phases
pub struct CompleteDecompiler {
    prg_rom: Vec<u8>,
    variables: HashMap<u8, Variable>,
    functions: BTreeMap<u16, Function>,
    variable_names: HashMap<u8, String>,
}

impl CompleteDecompiler {
    pub fn new(prg_rom: &[u8]) -> Self {
        eprintln!("Phase 1: Analyzing ROM...");

        // Phase 1: Analysis
        let accesses = scan_zeropage_accesses(prg_rom);
        let variables = infer_variables(&accesses);
        let functions = infer_functions(prg_rom);

        eprintln!("  Found {} variables", variables.len());
        eprintln!("  Found {} functions", functions.len());

        // Build variable names
        let mut variable_names = HashMap::new();
        for (addr, var) in &variables {
            variable_names.insert(*addr, var.name.clone());
        }

        Self {
            prg_rom: prg_rom.to_vec(),
            variables,
            functions,
            variable_names,
        }
    }

    /// Decompile the entire ROM to high-level NESL code
    pub fn decompile_complete(&mut self) -> String {
        let mut code = String::new();

        code.push_str("// Super Mario Bros - Complete Decompilation\n");
        code.push_str("// Generated by RustNES Advanced Decompiler\n");
        code.push_str("// Phases 1-5: Complete pipeline\n\n");

        // Variables
        code.push_str(&self.generate_variables());
        code.push_str("\n");

        // Functions (process a subset for testing)
        eprintln!("\nPhase 2-4: Processing functions...");

        let mut processed = 0;
        let max_functions = 10; // Start with a small set for testing

        for (addr, func) in self.functions.iter().take(max_functions) {
            eprintln!("  Processing function ${:04X} ({})...", addr, func.name);

            match self.decompile_function(*addr, func) {
                Ok(func_code) => {
                    code.push_str(&func_code);
                    code.push_str("\n");
                    processed += 1;
                }
                Err(e) => {
                    eprintln!("    Warning: {}", e);
                    // Fallback to simple version
                    code.push_str(&format!("fn {}() {{\n", func.name));
                    code.push_str(&format!("    // TODO: Function at ${:04X}\n", addr));
                    code.push_str(&format!("    // Error: {}\n", e));
                    code.push_str("}\n\n");
                }
            }
        }

        eprintln!("\nProcessed {}/{} functions successfully", processed, max_functions);

        // Main entry point
        code.push_str("// Main entry point\n");
        code.push_str("fn main() {\n");
        code.push_str("    reset();\n");
        code.push_str("    loop {\n");
        code.push_str("        // Game loop\n");
        code.push_str("    }\n");
        code.push_str("}\n");

        code
    }

    /// Decompile a single function through all phases
    fn decompile_function(&self, addr: u16, func: &Function) -> Result<String, String> {
        // Get instructions
        let instructions = self.extract_instructions(addr, func.size_bytes)?;

        if instructions.is_empty() {
            return Err("No instructions found".to_string());
        }

        // Phase 3: Register elimination
        let mut eliminator = RegisterEliminator::new();
        let ssa = eliminator.eliminate_registers(&instructions);

        if ssa.is_empty() {
            return Err("SSA conversion produced no statements".to_string());
        }

        // Phase 3: Data flow analysis and optimization
        let mut analyzer = DataFlowAnalyzer::new(ssa);
        analyzer.analyze();

        let after_const = analyzer.constant_propagation();

        let mut propagator = VariablePropagator::new();
        let after_copy = propagator.propagate_copies(&after_const);

        // Note: Dead code elimination can be added here
        // let optimized = analyzer.eliminate_dead_code();

        // Phase 4: High-level code generation
        let mut codegen = HighLevelCodeGen::new();
        let body = codegen.generate(&after_copy);

        // Detect parameters
        let mut param_detector = ParameterDetector::new();
        let params = param_detector.detect(&after_copy);

        // Build function signature
        let mut signature = format!("fn {}(", func.name);
        if !params.is_empty() {
            let param_strs: Vec<_> = params.iter()
                .map(|addr| {
                    let name = self.variable_names.get(addr)
                        .cloned()
                        .unwrap_or_else(|| format!("var_{:02X}", addr));
                    format!("{}: u8", name)
                })
                .collect();
            signature.push_str(&param_strs.join(", "));
        }
        signature.push_str(") {\n");

        let mut code = String::new();
        code.push_str(&format!("// Function at ${:04X}\n", addr));
        code.push_str(&signature);

        if body.is_empty() {
            code.push_str("    // Empty function\n");
        } else {
            code.push_str(&body);
            code.push('\n');
        }

        code.push_str("}\n");

        Ok(code)
    }

    fn extract_instructions(&self, addr: u16, max_size: usize) -> Result<Vec<(Instruction, u16)>, String> {
        let offset = self.addr_to_offset(addr);
        if offset >= self.prg_rom.len() {
            return Err(format!("Address ${:04X} out of bounds", addr));
        }

        let mut disasm = Disassembler::new(&self.prg_rom);
        let mut instructions = Vec::new();
        let mut pc = offset;
        let end = (offset + max_size).min(self.prg_rom.len());

        while pc < end {
            if let Some((instr, size)) = disasm.decode_at(pc) {
                // Extract the value for the instruction
                let val = if size > 1 && pc + 1 < self.prg_rom.len() {
                    if size == 2 {
                        self.prg_rom[pc + 1] as u16
                    } else {
                        // 3 bytes: little-endian
                        self.prg_rom[pc + 1] as u16 | ((self.prg_rom[pc + 2] as u16) << 8)
                    }
                } else {
                    0
                };

                instructions.push((instr.clone(), val));

                // Stop at return
                if matches!(instr, Instruction::RTS | Instruction::RTI) {
                    break;
                }

                pc += size;
            } else {
                break;
            }
        }

        Ok(instructions)
    }

    fn generate_variables(&self) -> String {
        let mut code = String::new();
        code.push_str("// ========== Variables ==========\n\n");

        let mut vars: Vec<_> = self.variables.values().collect();
        vars.sort_by_key(|v| v.addr);

        for var in vars.iter().take(30) {
            code.push_str(&format!("var {}: u8;  // ${:02X}\n", var.name, var.addr));
        }

        code
    }

    fn addr_to_offset(&self, addr: u16) -> usize {
        let prg_size = self.prg_rom.len();
        if addr >= 0xC000 && prg_size <= 16384 {
            (addr - 0xC000) as usize
        } else if addr >= 0x8000 {
            (addr - 0x8000) as usize
        } else {
            0
        }
    }
}

/// Generate complete decompiled code
pub fn decompile_complete(prg_rom: &[u8]) -> String {
    let mut decompiler = CompleteDecompiler::new(prg_rom);
    decompiler.decompile_complete()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_complete_pipeline() {
        // Simple test ROM
        let rom = vec![
            0xA9, 0x10,  // LDA #$10
            0x85, 0x50,  // STA $50
            0x60,        // RTS
        ];

        let decompiler = CompleteDecompiler::new(&rom);
        // Test that it doesn't panic
        assert!(decompiler.variables.len() > 0 || decompiler.functions.len() >= 0);
    }
}
