/// Encodes 8 rows of 8 pixel characters (`.`/`0`/space = 0, `1`-`3`) into NES 2bpp format.
pub fn encode_tile(rows: &[&str]) -> Result<[u8; 16], String> {
    if rows.len() != 8 {
        return Err(format!("a tile needs 8 rows of 8 pixels, found {} rows", rows.len()));
    }
    let mut out = [0u8; 16];
    for (y, row) in rows.iter().enumerate() {
        let pixels: Vec<char> = row.chars().collect();
        if pixels.len() != 8 {
            return Err(format!("tile row {} must have 8 pixels, found {}", y + 1, pixels.len()));
        }
        for (x, c) in pixels.iter().enumerate() {
            let v = match c {
                '.' | '0' | ' ' => 0,
                '1' => 1,
                '2' => 2,
                '3' => 3,
                other => return Err(format!("invalid pixel `{other}` in tile row {} (use . 1 2 3)", y + 1)),
            };
            let bit = 0x80 >> x;
            if v & 1 != 0 {
                out[y] |= bit;
            }
            if v & 2 != 0 {
                out[y + 8] |= bit;
            }
        }
    }
    Ok(out)
}

/// Builds 8KB of CHR: the font at tile index = ASCII code (lowercase reuses uppercase),
/// user tiles on top, and pattern table 1 as a copy of table 0.
pub fn build_chr(tiles: &[(u8, [u8; 16])]) -> Vec<u8> {
    let mut chr = vec![0u8; CHR_SIZE];
    let mut put = |index: usize, glyph: &[u8; 8]| {
        for (i, row) in glyph.iter().enumerate() {
            chr[index * 16 + i] = row.reverse_bits();
        }
    };
    for (i, glyph) in FONT.iter().enumerate() {
        put(0x20 + i, glyph);
    }
    for c in b'a'..=b'z' {
        put(c as usize, &FONT[(c - b'a' + b'A' - 0x20) as usize]);
    }
    // Status bar sprite-0 markers: one pixel in row 6 of tiles $7E (sprite) and $7F (background).
    chr[0x7E * 16 + 6] = 0x80;
    chr[0x7F * 16 + 6] = 0x80;
    for (index, data) in tiles {
        let at = *index as usize * 16;
        chr[at..at + 16].copy_from_slice(data);
    }
    let (t0, t1) = chr.split_at_mut(0x1000);
    t1.copy_from_slice(t0);
    chr
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn encodes_two_bitplanes_msb_first() {
        let t = encode_tile(&["0123....", "3.......", "........", "........", "........", "........", "........", "......21"]).unwrap();
        assert_eq!(t[0], 0b0101_0000);
        assert_eq!(t[8], 0b0011_0000);
        assert_eq!((t[1], t[9]), (0x80, 0x80));
        assert_eq!((t[7], t[15]), (0b0000_0001, 0b0000_0010));
    }

    #[test]
    fn rejects_bad_shapes_and_pixels() {
        assert!(encode_tile(&["........"; 7]).unwrap_err().contains("8 rows"));
        let mut rows = ["........"; 8];
        rows[2] = ".......";
        assert!(encode_tile(&rows).unwrap_err().contains("row 3"));
        rows[2] = "...4....";
        assert!(encode_tile(&rows).unwrap_err().contains("pixel"));
    }

    #[test]
    fn font_covers_printable_ascii_and_lowercase_maps_to_uppercase() {
        let chr = build_chr(&[]);
        assert!(chr[0x20 * 16..0x21 * 16].iter().all(|b| *b == 0), "space is blank");
        for c in b'!'..=b'_' {
            let g = &chr[c as usize * 16..c as usize * 16 + 8];
            assert!(g.iter().any(|b| *b != 0), "glyph {:?}", c as char);
        }
        assert_eq!(&chr[b'a' as usize * 16..b'a' as usize * 16 + 16], &chr[b'A' as usize * 16..b'A' as usize * 16 + 16]);
    }

    #[test]
    fn user_tiles_override_font() {
        let chr = build_chr(&[(0x41, [0xAA; 16])]);
        assert_eq!(&chr[0x410..0x420], &[0xAA; 16]);
        assert_eq!(&chr[0x1410..0x1420], &[0xAA; 16]);
    }
}
